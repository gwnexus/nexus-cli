/// Files and directories generated by AI coding agents / agentic tooling.
const AGENTIC_PATTERNS: &[&str] = &[
    // Claude Code / Anthropic
    ".claude/",
    "CLAUDE.md",
    // OpenCode
    ".opencode/",
    "opencode.json",
    "opencode.jsonc",
    // Nexus
    ".nexus/",
    "AGENTS.md",
    // Cursor
    ".cursorrules",
    ".cursorignore",
    // Kiro
    ".kiro/",
    // Roo
    ".roo/",
    ".roomodes",
    // Windsurf
    ".windsurfrules",
    // GitHub Copilot
    ".github/copilot-instructions.md",
    // Taskmaster AI
    ".taskmaster/",
    "taskmaster.config.yaml",
    "tasks/",
    ".taskmasterconfig",
    // RTK
    ".rtk/",
    "RTK.md",
];

/// Workspace file patterns to shadow (devbox/workspace stack).
const WORKSPACE_PATTERNS: &[&str] = &["devbox.json", "devbox.lock", ".devbox/", "scripts/devbox/"];

/// Marker comments used to delimit our block in .git/info/exclude.
const MARKER_START: &str = "# >>> nexus shadow";
const MARKER_END: &str = "# <<< nexus shadow";

/// Marker comments for workspace shadow block.
const WS_MARKER_START: &str = "# >>> nexus workspace shadow";
const WS_MARKER_END: &str = "# <<< nexus workspace shadow";

// ---------------------------------------------------------------------------
// Public entry points — agentic shadow
// ---------------------------------------------------------------------------

/// Enable shadow mode (agentic files).
pub fn on() -> anyhow::Result<()> {
    local_on(LocalTarget::Agentic, false, true)
}

/// The two local exclude blocks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum LocalTarget {
    Agentic,
    Workspace,
}

impl LocalTarget {
    fn patterns(self) -> &'static [&'static str] {
        match self {
            Self::Agentic => AGENTIC_PATTERNS,
            Self::Workspace => WORKSPACE_PATTERNS,
        }
    }
    fn markers(self) -> (&'static str, &'static str) {
        match self {
            Self::Agentic => (MARKER_START, MARKER_END),
            Self::Workspace => (WS_MARKER_START, WS_MARKER_END),
        }
    }
    fn label(self) -> &'static str {
        match self {
            Self::Agentic => "Shadow mode",
            Self::Workspace => "Workspace shadow",
        }
    }
    fn flag(self) -> &'static str {
        match self {
            Self::Agentic => "agentic",
            Self::Workspace => "workspace",
        }
    }
}

/// Switch a local block on: write it if missing, take files without
/// commit history out of the index (all matching files with `untrack`),
/// and explain what git still tracks. With `hint_if_active` false an
/// already active block is left alone silently (the `nexus pull` path).
fn local_on(target: LocalTarget, untrack: bool, hint_if_active: bool) -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");
    if let Some(parent) = exclude_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let (start, end) = target.markers();
    let patterns = target.patterns();
    let active = is_block_active(&exclude_path, start);
    if active && !hint_if_active {
        return Ok(());
    }
    let bullet = match target {
        LocalTarget::Agentic => style("●").green().bold(),
        LocalTarget::Workspace => style("●").magenta().bold(),
    };
    if active {
        println!("{bullet} {} is already enabled.", target.label());
    } else {
        write_exclude_block(&exclude_path, start, end, patterns)?;
    }
    let report = untrack_patterns(patterns, untrack)?;
    if !active {
        println!("{bullet} {} {}.", target.label(), style("enabled").bold());
        println!(
            "  {} {} patterns added to .git/info/exclude",
            patterns.len(),
            target.flag()
        );
    }
    if report.removed > 0 {
        println!(
            "  {} file(s) removed from the git index (kept on disk; your next commit removes them from the repository)",
            report.removed
        );
        if untrack {
            println!(
                "    {}",
                style("Review with git status, then commit, e.g.: git commit -m \"chore: stop tracking local files\"").dim()
            );
        }
    }
    print_tracked_hint(&report, target.flag());
    if !active {
        println!(
            "  {}",
            style("Note: .git/info/exclude is local and will not be committed.").dim()
        );
    }
    Ok(())
}

/// Disable shadow mode (agentic files).
pub fn off() -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");

    if !is_block_active(&exclude_path, MARKER_START) {
        println!("{} Shadow mode is not currently enabled.", style("○").dim());
        return Ok(());
    }

    // Remove our block from the exclude file
    let content = fs::read_to_string(&exclude_path)?;
    let cleaned = remove_block(&content, MARKER_START, MARKER_END);
    fs::write(&exclude_path, &cleaned)?;

    // Re-track files that exist on disk (best effort)

    println!(
        "{} Shadow mode {}.",
        style("○").yellow().bold(),
        style("disabled").yellow().bold()
    );
    println!("  Agentic patterns removed from .git/info/exclude");
    print_add_hints(&untracked_patterns(AGENTIC_PATTERNS));

    Ok(())
}

/// The local blocks. With `server_level` the server decides the agentic
/// excludes, so the local agentic block is labelled as the legacy mode
/// instead of reading like a contradiction to the server level.
fn local_status(server_level: bool) -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");

    let agentic_active = is_block_active(&exclude_path, MARKER_START);
    let workspace_active = is_block_active(&exclude_path, WS_MARKER_START);
    let workspace_label = if server_level {
        "Workspace shadow (devbox files)"
    } else {
        "Workspace shadow"
    };

    if server_level {
        if agentic_active {
            println!(
                "{} Local shadow block (legacy): {}",
                style("●").yellow().bold(),
                style("active").yellow().bold()
            );
            println!("  Shadowed patterns:");
            for pat in AGENTIC_PATTERNS {
                println!("    {}", style(pat).dim());
            }
        } else {
            println!(
                "{} Local shadow block (legacy): {}",
                style("○").dim(),
                style("none").dim()
            );
        }
    } else if agentic_active {
        println!(
            "{} Shadow mode is {}.",
            style("●").green().bold(),
            style("enabled").green().bold()
        );
        println!("  Shadowed patterns:");
        for pat in AGENTIC_PATTERNS {
            println!("    {}", style(pat).dim());
        }
    } else {
        println!(
            "{} Shadow mode is {}.",
            style("○").dim(),
            style("disabled").dim()
        );
    }

    if workspace_active {
        println!(
            "{} {workspace_label} is {}.",
            style("●").magenta().bold(),
            style("enabled").magenta().bold()
        );
        println!("  Workspace patterns:");
        for pat in WORKSPACE_PATTERNS {
            println!("    {}", style(pat).dim());
        }
    } else {
        println!(
            "{} {workspace_label} is {}.",
            style("○").dim(),
            style("disabled").dim()
        );
    }

    Ok(())
}

