/// Enable workspace shadow mode (devbox files excluded from git), as
/// `nexus pull` does for a fork in shadow mode: silent when already on.
pub fn workspace_on() -> anyhow::Result<()> {
    local_on(LocalTarget::Workspace, false, false)
}

/// Disable workspace shadow mode.
pub fn workspace_off() -> anyhow::Result<()> {
    let repo = current_repo()?;
    let exclude_path = repo.exclude.clone();

    if !is_block_active(&exclude_path, WS_MARKER_START) {
        println!(
            "{} Workspace shadow is not currently enabled.",
            style("○").dim()
        );
        return Ok(());
    }

    let content = read_exclude(&exclude_path)?;
    let cleaned = remove_block(&content, WS_MARKER_START, WS_MARKER_END);
    fs::write(&exclude_path, &cleaned)?;

    println!(
        "{} Workspace shadow {}.",
        style("○").yellow().bold(),
        style("disabled").yellow().bold()
    );
    println!("  Workspace patterns removed from .git/info/exclude");
    print_add_hints(&untracked_patterns_in(WORKSPACE_PATTERNS, &repo.work_tree));

    Ok(())
}

/// Check whether workspace shadow is currently active.
#[allow(dead_code)]
pub fn is_workspace_shadow_active() -> anyhow::Result<bool> {
    Ok(is_block_active(&current_repo()?.exclude, WS_MARKER_START))
}

/// Protect a file that carries the API token (`.mcp.json`, `opencode.json`):
/// owner-only permissions, listed in `.git/info/exclude` of the repository
/// containing `workspace`, and a warning when git already tracks it (an
/// exclude does not untrack).
/// The token value to write into `rel`: the token itself, or `reference`
/// (an environment reference such as `${NEXUS_PRIVATE_TOKEN}`) when git
/// tracks the file, so a commit cannot publish the token. Says so once per
/// call.
pub fn token_for_file(workspace: &Path, rel: &str, token: &str, reference: &str) -> String {
    let path = workspace.join(rel);
    if path.is_file() && nexus_core::config::trust::is_git_tracked(&path) {
        println!(
            "   {} {rel} is tracked by git: the API token is not written into it (it reads {reference} instead); untrack it with git rm --cached {rel}, then run nexus pull",
            style("!").bold().red()
        );
        return reference.to_string();
    }
    token.to_string()
}

pub fn protect_token_file(workspace: &Path, rel: &str, excludes: &[&str]) {
    let path = workspace.join(rel);
    #[cfg(unix)]
    if path.is_file() {
        use std::os::unix::fs::PermissionsExt;
        if let Err(e) = fs::set_permissions(&path, fs::Permissions::from_mode(0o600)) {
            println!(
                "   {} {rel} contains the API token, but its permissions could not be restricted to 0600: {e}",
                style("!").bold().red()
            );
        }
    }
    if let Err(e) = try_ensure_git_excluded_in(workspace, excludes, "token-bearing files") {
        println!(
            "   {} {rel} contains the API token, but it could not be added to .git/info/exclude: {e}",
            style("!").bold().red()
        );
    }
    warn_if_token_file_tracked(workspace, rel);
}

fn warn_if_token_file_tracked(workspace: &Path, rel: &str) {
    if workspace.join(rel).is_file()
        && super::shadow_guard::git_in(workspace)
            .args([
                "--literal-pathspecs",
                "ls-files",
                "--error-unmatch",
                "--",
                rel,
            ])
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok_and(|s| s.success())
    {
        println!(
            "   {} {rel} contains the API token and is tracked by git; untrack it: git rm --cached {rel}",
            style("!").bold().red()
        );
    }
}

/// Write a file that carries a token (`.mcp.json`, `opencode.json`,
/// `.env.nexus.local`): first make sure git ignores it (`excludes` go into
/// `.git/info/exclude`), then write `content` atomically with mode 0600. A
/// symlink at the destination is refused, so the token cannot land outside
/// the workspace, and nothing is written when the exclude cannot be
/// recorded. Callers choose the token value with [`token_for_file`] first,
/// so a file that git already tracks only receives a reference.
pub fn write_token_file(
    workspace: &Path,
    rel: &str,
    content: &str,
    excludes: &[&str],
) -> anyhow::Result<()> {
    let path = workspace.join(rel);
    if fs::symlink_metadata(&path).is_ok_and(|m| m.file_type().is_symlink()) {
        anyhow::bail!(
            "{rel} is a symlink; refusing to write a token through it (replace it with a regular file)"
        );
    }
    let exclude_failed = |e: std::io::Error| {
        anyhow::anyhow!("{rel} carries a token, but it could not be git-excluded: {e}")
    };
    try_ensure_git_excluded_in(workspace, excludes, "token-bearing files")
        .map_err(exclude_failed)?;
    // A later `!` rule (or a .gitignore negation) can still un-ignore it.
    // Inside a repository the answer must be known before the token lands.
    let in_repo = exclude_file_for(workspace)
        .map_err(exclude_failed)?
        .is_some();
    if in_repo && git_ignores(workspace, rel).is_none() {
        anyhow::bail!(
            "{rel} carries a token, but git could not confirm that it ignores the file \
             (is git installed and the repository readable?); nothing was written"
        );
    }
    if git_ignores(workspace, rel) == Some(false) {
        write_excludes(workspace, excludes, "token-bearing files", true).map_err(exclude_failed)?;
        if git_ignores(workspace, rel) == Some(false) {
            anyhow::bail!(
                "{rel} carries a token, but git does not ignore it (a negating rule in \
                 .gitignore or .git/info/exclude wins); remove that rule and run again"
            );
        }
    }
    nexus_core::fsutil::write_private_atomic(&path, content.as_bytes())
        .map_err(|e| anyhow::anyhow!("failed to write {rel}: {e}"))?;
    warn_if_token_file_tracked(workspace, rel);
    Ok(())
}

/// Ensure that the given file paths are listed in `.git/info/exclude` of the
/// repository containing `start`, with the reason shown in the comment line
/// above the added entries. Best effort: outside a git repository, or when
/// the exclude file cannot be written, nothing happens.
pub fn ensure_git_excluded_in(start: &Path, paths: &[&str], reason: &str) {
    let _ = try_ensure_git_excluded_in(start, paths, reason);
}

/// [`ensure_git_excluded_in`] that reports a failed write. Outside a git
/// repository there is nothing to do, which is not an error.
pub fn try_ensure_git_excluded_in(
    start: &Path,
    paths: &[&str],
    reason: &str,
) -> std::io::Result<()> {
    write_excludes(start, paths, reason, false)
}

/// The exclude file git uses for the repository containing `start`, also
/// in linked worktrees and submodules (where `.git` is a file). `None`
/// outside a repository; an error when git metadata exists above `start`
/// but cannot be resolved.
fn exclude_file_for(start: &Path) -> std::io::Result<Option<PathBuf>> {
    Ok(repo_at(start)?.map(|r| r.exclude))
}

/// Whether git ignores `rel` in the repository containing `workspace`,
/// by the ignore rules alone (also for a tracked file). `None` outside a
/// repository or when git cannot answer.
fn git_ignores(workspace: &Path, rel: &str) -> Option<bool> {
    let status = super::shadow_guard::git_in(workspace)
        .args(["check-ignore", "-q", "--no-index", "--"])
        .arg(rel)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .ok()?;
    match status.code() {
        Some(0) => Some(true),
        Some(1) => Some(false),
        _ => None,
    }
}

/// Add `paths` to the exclude file; with `force`, append them again even
/// when they are listed already (so they come after a negating `!` line).
fn write_excludes(start: &Path, paths: &[&str], reason: &str, force: bool) -> std::io::Result<()> {
    let Some(exclude_path) = exclude_file_for(start)? else {
        return Ok(());
    };

    // Ensure parent directory exists
    if let Some(parent) = exclude_path.parent() {
        fs::create_dir_all(parent)?;
    }

    let existing = read_exclude(&exclude_path)?;

    let mut additions = Vec::new();
    for path in paths {
        if force || !existing.lines().any(|line| line.trim() == *path) {
            additions.push(*path);
        }
    }

    if additions.is_empty() {
        return Ok(());
    }

    let mut content = existing;
    if !content.ends_with('\n') && !content.is_empty() {
        content.push('\n');
    }
    content.push_str(&format!("# nexus: {reason} (auto-added)\n"));
    for path in additions {
        content.push_str(path);
        content.push('\n');
    }
    fs::write(&exclude_path, content)
}

