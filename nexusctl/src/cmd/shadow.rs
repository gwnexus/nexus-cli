//! `nexus shadow on|ai|nexus|off|status` — hide agentic scaffold files from Git.
//!
//! Since ADR-0125 (NEXUS-APP dispatch 15497fa2) the shadow level is a
//! project setting on the server (`policy.shadow`: `off` | `ai` | `nexus`)
//! and `nexus shadow` is a thin client of it: it sets the level, then
//! applies the server's `af_export.git_exclude` list as a managed block in
//! `.git/info/exclude` (local, never committed). `nexus pull` applies the
//! same block on every run. Files already tracked in git are never
//! untracked automatically; a `git rm -r --cached` hint is printed instead.
//!
//! Backends without `policy.shadow` (or an unlinked workspace) keep the
//! old local mode: `on` adds a fixed pattern block and untracks matching
//! files without history, `off` removes it and re-adds them.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use console::style;

// ---------------------------------------------------------------------------
// Agentic file patterns to shadow
// ---------------------------------------------------------------------------

/// Files and directories generated by AI coding agents / agentic tooling.
const AGENTIC_PATTERNS: &[&str] = &[
    // Claude Code / Anthropic
    ".claude/",
    "CLAUDE.md",
    // OpenCode
    ".opencode/",
    "opencode.json",
    "opencode.jsonc",
    // Nexus
    ".nexus/",
    "AGENTS.md",
    // Cursor
    ".cursorrules",
    ".cursorignore",
    // Kiro
    ".kiro/",
    // Roo
    ".roo/",
    ".roomodes",
    // Windsurf
    ".windsurfrules",
    // GitHub Copilot
    ".github/copilot-instructions.md",
    // Taskmaster AI
    ".taskmaster/",
    "taskmaster.config.yaml",
    "tasks/",
    ".taskmasterconfig",
    // RTK
    ".rtk/",
    "RTK.md",
];

/// Workspace file patterns to shadow (devbox/workspace stack).
const WORKSPACE_PATTERNS: &[&str] = &["devbox.json", "devbox.lock", ".devbox/", "scripts/devbox/"];

/// Marker comments used to delimit our block in .git/info/exclude.
const MARKER_START: &str = "# >>> nexus shadow";
const MARKER_END: &str = "# <<< nexus shadow";

/// Marker comments for workspace shadow block.
const WS_MARKER_START: &str = "# >>> nexus workspace shadow";
const WS_MARKER_END: &str = "# <<< nexus workspace shadow";

// ---------------------------------------------------------------------------
// Public entry points — agentic shadow
// ---------------------------------------------------------------------------

/// Enable shadow mode (agentic files).
pub fn on() -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");

    // Ensure .git/info/ exists
    if let Some(parent) = exclude_path.parent() {
        fs::create_dir_all(parent)?;
    }

    // Check if already active
    if is_block_active(&exclude_path, MARKER_START) {
        println!(
            "{} Shadow mode is already enabled.",
            style("●").green().bold()
        );
        return Ok(());
    }

    // Build and write the exclude block
    write_exclude_block(&exclude_path, MARKER_START, MARKER_END, AGENTIC_PATTERNS)?;

    // Remove already-tracked files from the index (best effort)
    let removed = untrack_patterns(AGENTIC_PATTERNS)?;

    println!(
        "{} Shadow mode {}.",
        style("●").green().bold(),
        style("enabled").green().bold()
    );
    println!(
        "  {} agentic patterns added to .git/info/exclude",
        AGENTIC_PATTERNS.len()
    );
    if removed > 0 {
        println!(
            "  {} previously tracked file(s) removed from index (files kept on disk)",
            removed
        );
    }
    println!(
        "  {}",
        style("Note: .git/info/exclude is local and will not be committed.").dim()
    );

    Ok(())
}

/// Disable shadow mode (agentic files).
pub fn off() -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");

    if !is_block_active(&exclude_path, MARKER_START) {
        println!("{} Shadow mode is not currently enabled.", style("○").dim());
        return Ok(());
    }

    // Remove our block from the exclude file
    let content = fs::read_to_string(&exclude_path)?;
    let cleaned = remove_block(&content, MARKER_START, MARKER_END);
    fs::write(&exclude_path, &cleaned)?;

    // Re-track files that exist on disk (best effort)
    let re_added = retrack_patterns(AGENTIC_PATTERNS)?;

    println!(
        "{} Shadow mode {}.",
        style("○").yellow().bold(),
        style("disabled").yellow().bold()
    );
    println!("  Agentic patterns removed from .git/info/exclude");
    if re_added > 0 {
        println!("  {} file(s) re-added to Git tracking", re_added);
    }

    Ok(())
}

/// Show current shadow mode status (agentic files).
pub fn status() -> anyhow::Result<()> {
    local_status(false)
}

/// The local blocks. With `server_level` the server decides the agentic
/// excludes, so the local agentic block is labelled as the legacy mode
/// instead of reading like a contradiction to the server level.
fn local_status(server_level: bool) -> anyhow::Result<()> {
    let git_dir = find_git_dir()?;
    let exclude_path = git_dir.join("info").join("exclude");

    let agentic_active = is_block_active(&exclude_path, MARKER_START);
    let workspace_active = is_block_active(&exclude_path, WS_MARKER_START);
    let workspace_label = if server_level {
        "Workspace shadow (devbox files)"
    } else {
        "Workspace shadow"
    };

    if server_level {
        if agentic_active {
            println!(
                "{} Local shadow block (legacy): {}",
                style("●").yellow().bold(),
                style("active").yellow().bold()
            );
            println!("  Shadowed patterns:");
            for pat in AGENTIC_PATTERNS {
                println!("    {}", style(pat).dim());
            }
        } else {
            println!(
                "{} Local shadow block (legacy): {}",
                style("○").dim(),
                style("none").dim()
            );
        }
    } else if agentic_active {
        println!(
            "{} Shadow mode is {}.",
            style("●").green().bold(),
            style("enabled").green().bold()
        );
        println!("  Shadowed patterns:");
        for pat in AGENTIC_PATTERNS {
            println!("    {}", style(pat).dim());
        }
    } else {
        println!(
            "{} Shadow mode is {}.",
            style("○").dim(),
            style("disabled").dim()
        );
    }

    if workspace_active {
        println!(
            "{} {workspace_label} is {}.",
            style("●").magenta().bold(),
            style("enabled").magenta().bold()
        );
        println!("  Workspace patterns:");
        for pat in WORKSPACE_PATTERNS {
            println!("    {}", style(pat).dim());
        }
    } else {
        println!(
            "{} {workspace_label} is {}.",
            style("○").dim(),
            style("disabled").dim()
        );
    }

    Ok(())
}

