/// Marker comments for the block holding `af_export.git_exclude`.
const SERVER_MARKER_START: &str = "# >>> nexus managed exclude (server)";
const SERVER_MARKER_END: &str = "# <<< nexus managed exclude (server)";
const LOCAL_MARKER_START: &str = "# >>> nexus local scripts";
const LOCAL_MARKER_END: &str = "# <<< nexus local scripts";

/// What [`apply_server_excludes`] changed.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct ServerExcludeReport {
    /// Paths newly written to the managed block.
    pub added: Vec<String>,
    /// Paths dropped from the block (the server no longer sends them).
    pub removed: Vec<String>,
    /// Paths refused as unsafe (absolute, `..`, negation, comments).
    pub rejected: Vec<String>,
    /// Excluded paths that git still tracks (an exclude does not untrack).
    pub tracked: Vec<String>,
    /// The validated paths of this export, for `--untrack`.
    pub entries: Vec<String>,
    /// Why the exclude file was not updated; nothing may be untracked then.
    pub error: Option<String>,
}

/// Whether a server-sent exclude entry is a plain relative path pattern.
/// Refuses anything that could change the meaning of the exclude file or
/// point outside the repository: empty, absolute, `..` segments, line
/// breaks, negation (`!`) and comments (`#`).
pub fn valid_exclude_path(path: &str) -> bool {
    let p = path.trim();
    !p.is_empty()
        && !p.contains(['\n', '\r', '\\'])
        && !p.starts_with(['/', '!', '#'])
        && !p.split('/').any(|seg| seg == "..")
        && !(p.len() > 1 && p.as_bytes()[1] == b':')
}

/// Entries of a marker-delimited block.
fn block_entries(content: &str, marker_start: &str, marker_end: &str) -> Vec<String> {
    let mut inside = false;
    let mut entries = Vec::new();
    for line in content.lines() {
        let line = line.trim();
        if line == marker_start {
            inside = true;
        } else if line == marker_end {
            inside = false;
        } else if inside && !line.is_empty() && !line.starts_with('#') {
            entries.push(line.to_string());
        }
    }
    entries
}

/// Rewrite the managed block in `.git/info/exclude` of the repository
/// containing `workspace` so it holds exactly the valid `paths` not already
/// listed elsewhere in the file (an empty list removes the block), and
/// report which excluded paths git still tracks. Best effort: outside a git
/// repository, or when the file cannot be written, nothing happens.
pub fn apply_server_excludes(workspace: &Path, paths: &[String]) -> ServerExcludeReport {
    apply_exclude_block(
        workspace,
        SERVER_MARKER_START,
        SERVER_MARKER_END,
        paths,
        true,
    )
}

/// Rewrite the `.git/info/exclude` block for machine-local scripts so it
/// holds exactly `paths` (an empty list removes the block). The block is
/// the lifecycle source for these files, so a path listed elsewhere in the
/// file is still written here.
pub fn apply_local_script_excludes(workspace: &Path, paths: &[String]) -> ServerExcludeReport {
    apply_exclude_block(
        workspace,
        LOCAL_MARKER_START,
        LOCAL_MARKER_END,
        paths,
        false,
    )
}

/// Rewrite one marker-delimited block of `.git/info/exclude`; with
/// `dedupe`, paths already listed outside the block are left out.
fn apply_exclude_block(
    workspace: &Path,
    marker_start: &str,
    marker_end: &str,
    paths: &[String],
    dedupe: bool,
) -> ServerExcludeReport {
    let mut report = ServerExcludeReport::default();
    let repo = match repo_at(workspace) {
        Ok(Some(repo)) => repo,
        Ok(None) => return report,
        Err(e) => {
            report.error = Some(e.to_string());
            return report;
        }
    };
    let exclude_path = repo.exclude.clone();
    let existing = match read_exclude(&exclude_path) {
        Ok(text) => text,
        Err(e) => {
            report.error = Some(e.to_string());
            return report;
        }
    };
    let previous = block_entries(&existing, marker_start, marker_end);
    let outside = remove_block(&existing, marker_start, marker_end);

    let mut valid: Vec<String> = Vec::new();
    for raw in paths {
        let p = raw.trim().to_string();
        if !valid_exclude_path(&p) {
            report.rejected.push(raw.clone());
        } else if !valid.contains(&p) {
            valid.push(p);
        }
    }
    let wanted: Vec<String> = valid
        .iter()
        .filter(|p| !dedupe || !outside.lines().any(|l| l.trim() == p.as_str()))
        .cloned()
        .collect();

    report.added = wanted
        .iter()
        .filter(|p| !previous.contains(p))
        .cloned()
        .collect();
    report.removed = previous
        .iter()
        .filter(|p| !wanted.contains(p))
        .cloned()
        .collect();

    let mut content = outside;
    if !wanted.is_empty() {
        if !content.is_empty() && !content.ends_with("\n\n") {
            content.push('\n');
        }
        content.push_str(marker_start);
        content.push('\n');
        for p in &wanted {
            content.push_str(p);
            content.push('\n');
        }
        content.push_str(marker_end);
        content.push('\n');
    }
    if content != existing {
        let written = match exclude_path.parent() {
            Some(parent) => fs::create_dir_all(parent),
            None => Ok(()),
        }
        .and_then(|()| fs::write(&exclude_path, &content));
        if let Err(e) = written {
            return ServerExcludeReport {
                rejected: report.rejected,
                error: Some(format!("{}: {e}", exclude_path.display())),
                ..Default::default()
            };
        }
    }

    report.tracked = valid
        .iter()
        .filter(|p| is_pattern_tracked(&repo.work_tree, p))
        .cloned()
        .collect();
    report.entries = valid;
    report
}

/// Print what [`apply_server_excludes`] did (pull and `nexus shadow`).
pub fn print_server_exclude_report(report: &ServerExcludeReport, shadow: Option<&str>) {
    let level = shadow
        .filter(|l| !l.is_empty())
        .map(|l| format!(" (shadow: {l})"))
        .unwrap_or_default();
    if !report.added.is_empty() || !report.removed.is_empty() {
        println!(
            "   {} .git/info/exclude: +{}/-{} server path(s){}",
            style("~").bold().cyan(),
            report.added.len(),
            report.removed.len(),
            level
        );
    }
    for path in &report.rejected {
        println!(
            "   {} ignored unsafe exclude entry from the server: {:?}",
            style("!").bold().yellow(),
            path
        );
    }
    if let Some(e) = &report.error {
        println!(
            "   {} .git/info/exclude not updated, nothing untracked: {e}",
            style("!").bold().yellow()
        );
    }
    print_tracked_excluded(&report.tracked);
}

/// One warning for excluded paths git still tracks, with both ways out:
/// `git add -u` keeps them tracked, `nexus pull --untrack-shadowed` takes
/// them out of the index (never done automatically).
pub fn print_tracked_excluded(paths: &[String]) {
    if paths.is_empty() {
        return;
    }
    println!(
        "   {} {} excluded path(s) still tracked by git: {}",
        style("!").bold().yellow(),
        paths.len(),
        paths.join(", ")
    );
    println!("     git add <path> refuses them; stage their changes with: git add -u");
    println!("     or untrack them (kept on disk, not committed): nexus pull --untrack-shadowed");
}

/// Server exclude entries that git still tracks in the repository of
/// `workspace` (for `nexus status`).
pub fn tracked_excluded(workspace: &Path) -> Vec<String> {
    let Ok(Some(repo)) = repo_at(workspace) else {
        return Vec::new();
    };
    server_exclude_entries(workspace)
        .into_iter()
        .filter(|p| is_pattern_tracked(&repo.work_tree, p))
        .collect()
}

/// The server exclude block's entries for the repository containing
/// `workspace` (for `nexus shadow status`).
pub fn server_exclude_entries(workspace: &Path) -> Vec<String> {
    repo_at(workspace)
        .ok()
        .flatten()
        .and_then(|r| read_exclude(&r.exclude).ok())
        .map(|c| block_entries(&c, SERVER_MARKER_START, SERVER_MARKER_END))
        .unwrap_or_default()
}

/// Map a `nexus shadow` subcommand to a `policy.shadow` value
/// (`on` = `ai`).
pub fn policy_value(action: &str) -> Option<&'static str> {
    match action {
        "on" | "ai" => Some("ai"),
        "nexus" => Some("nexus"),
        "off" => Some("off"),
        _ => None,
    }
}

/// `nexus shadow on|ai|nexus|off`: set `policy.shadow` on the server and
/// apply the resulting `git_exclude` list now. Falls back to the local
/// mode when the workspace is not linked or the backend has no
/// `policy.shadow` setting.
pub async fn set_level(
    api_url: &str,
    action: &str,
    assume_yes: bool,
) -> anyhow::Result<Option<ServerExcludeReport>> {
    let level =
        policy_value(action).ok_or_else(|| anyhow::anyhow!("unknown shadow level '{action}'"))?;
    if !super::env_cmd::has_setting(api_url, "policy.shadow")
        .await
        .unwrap_or(false)
    {
        println!(
            "   {} No server shadow setting (workspace not linked or backend without policy.shadow); using local shadow mode.",
            style("i").bold().blue()
        );
        if level == "off" {
            off()?;
        } else {
            on()?;
        }
        return Ok(None);
    }

    super::env_cmd::set(api_url, "policy.shadow", level, false, assume_yes).await?;
    let workspace = std::env::current_dir()?;
    let (project_id, client) = super::env_cmd::connect(api_url)?;
    let export = client.export_agent_files(&project_id).await?;
    let report = apply_server_excludes(&workspace, &export.git_exclude);
    print_server_exclude_report(&report, export.shadow.as_deref());

    // The old local block would keep hiding the agentic files.
    if level == "off" {
        let exclude_path = repo_at(&workspace)?
            .ok_or_else(|| anyhow::anyhow!("Not inside a Git repository."))?
            .exclude;
        if is_block_active(&exclude_path, MARKER_START) {
            let content = read_exclude(&exclude_path)?;
            fs::write(
                &exclude_path,
                remove_block(&content, MARKER_START, MARKER_END),
            )?;
            println!(
                "   {} removed the local shadow block from .git/info/exclude (files stay untracked; git add them if wanted)",
                style("~").bold().cyan()
            );
        }
    }
    println!(
        "{} Shadow level {}.",
        style("●").green().bold(),
        style(level).bold()
    );
    // The guard follows the level right away (cache and commit-msg hook),
    // then the effective state, also when the level did not change.
    let agentic_root = agentic_root_of(&export);
    // An explicit `nexus shadow` command by the operator: the hook is part
    // of what was asked for.
    super::shadow_guard::sync(
        &workspace,
        &agentic_root,
        export.shadow_guard.as_ref(),
        true,
    );
    super::shadow_guard::print_state(
        super::shadow_guard::repo_root(&workspace).as_deref(),
        export.shadow.as_deref().unwrap_or(level),
        export.shadow_guard.as_ref(),
    );
    Ok(Some(report))
}

