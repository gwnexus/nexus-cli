/// What `nexus shadow on|off` hides.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum ShadowTarget {
    /// Agentic files (.claude/, .nexus/, AGENTS.md, CLAUDE.md, ...).
    #[value(alias = "ai", alias = "agentic-files")]
    Agentic,
    /// Devbox workspace files (devbox.json, devbox.lock, .devbox/, scripts/devbox/).
    Workspace,
    /// Nexus internals in commit messages and tracked files (includes agentic).
    Nexus,
}

impl ShadowTarget {
    const ALL: [ShadowTarget; 3] = [Self::Agentic, Self::Workspace, Self::Nexus];
}

/// Project setting for the workspace target, used once the backend offers it.
const WORKSPACE_SETTING: &str = "policy.shadow_workspace";

/// Line in `.git/info/exclude` recording that workspace shadow was switched
/// off locally, so `nexus pull` does not switch it on again for a fork in
/// shadow mode.
const WS_OPT_OUT: &str = "# nexus workspace shadow: off";

/// Print a deprecation note for an old shadow command.
pub fn deprecated(old: &str, new: &str) {
    println!(
        "   {} {old} is deprecated; use {new}",
        style("i").bold().blue()
    );
}

/// The `policy.shadow` level after switching targets on or off. `nexus`
/// includes `agentic`: switching `nexus` on raises the level to `nexus`,
/// switching `agentic` off drops it to `off`, switching `nexus` off keeps
/// `agentic`.
pub fn next_level(current: &str, on: bool, agentic: bool, nexus: bool) -> &'static str {
    let current = match current {
        "nexus" => "nexus",
        "ai" => "ai",
        _ => "off",
    };
    match (on, agentic, nexus) {
        (true, _, true) => "nexus",
        (true, true, false) if current == "nexus" => "nexus",
        (true, true, false) => "ai",
        (false, true, _) => "off",
        (false, false, true) if current == "nexus" => "ai",
        _ => current,
    }
}

/// `nexus shadow on|off [--target ...] [--all] [--dry-run]`. Without
/// targets (or with `--all`) every target is switched.
pub async fn switch(
    api_url: &str,
    on: bool,
    targets: &[ShadowTarget],
    all: bool,
    dry_run: bool,
    untrack: bool,
    assume_yes: bool,
) -> anyhow::Result<()> {
    let targets: &[ShadowTarget] = if targets.is_empty() || all {
        if on && !all {
            println!(
                "   {} nexus shadow on switches all targets (agentic, workspace, nexus); nexus shadow on --target agentic only hides the agentic files",
                style("i").bold().blue()
            );
        }
        &ShadowTarget::ALL
    } else {
        targets
    };
    let has = |t| targets.contains(&t);
    let (agentic, nexus) = (has(ShadowTarget::Agentic), has(ShadowTarget::Nexus));
    let settings = super::env_cmd::snapshot(api_url).await;
    let has_setting = |key: &str| {
        settings
            .as_ref()
            .is_some_and(|s| s.schema.iter().any(|x| x.key == key))
    };
    if dry_run {
        println!("{} Dry run, nothing is changed:", style(">>").bold().cyan());
        if on && untrack {
            println!("   --untrack: tracked files of the switched targets are taken out of the git index");
        }
    }

    if agentic || nexus {
        if has_setting("policy.shadow") {
            let current = settings
                .as_ref()
                .and_then(|s| s.settings.get("policy.shadow"))
                .and_then(|v| v.as_str())
                .unwrap_or("off");
            let level = next_level(current, on, agentic, nexus);
            if on && nexus && !agentic {
                println!(
                    "   {} nexus includes agentic: the agentic files are hidden too",
                    style("i").bold().blue()
                );
            }
            if !on && agentic && !nexus && current == "nexus" {
                println!(
                    "   {} switching agentic off also switches nexus off (nexus includes agentic)",
                    style("i").bold().blue()
                );
            }
            if dry_run {
                if level == current {
                    println!("   policy.shadow: {level} (unchanged)");
                } else {
                    println!("   policy.shadow: {current} -> {level}");
                }
            } else {
                let report = set_level(api_url, level, assume_yes).await?;
                if let Some(report) = report.filter(|r| on && untrack && r.error.is_none()) {
                    // Only the agentic and nexus paths: the workspace paths
                    // are untracked when that target is switched.
                    let entries: Vec<String> = report
                        .entries
                        .into_iter()
                        .filter(|e| !is_workspace_entry(e))
                        .collect();
                    untrack_server_paths(&std::env::current_dir()?, &entries)?;
                }
            }
        } else {
            if nexus {
                println!(
                    "   {} nexus: needs a linked project on a backend with policy.shadow; skipped",
                    style("!").yellow()
                );
            }
            if agentic {
                if dry_run {
                    println!(
                        "   agentic: {} the local shadow block in .git/info/exclude",
                        if on { "add" } else { "remove" }
                    );
                } else {
                    println!(
                        "   {} No server shadow setting (workspace not linked or backend without policy.shadow); using local shadow mode.",
                        style("i").bold().blue()
                    );
                    if on {
                        local_on(LocalTarget::Agentic, untrack, true)?;
                    } else {
                        off()?;
                    }
                }
            }
        }
    }

    if has(ShadowTarget::Workspace) {
        let server = has_setting(WORKSPACE_SETTING);
        if dry_run {
            if server {
                println!("   {WORKSPACE_SETTING}: -> {on}");
                println!(
                    "   workspace: the server exclude list {} the workspace paths",
                    if on { "adds" } else { "drops" }
                );
            } else {
                println!(
                    "   workspace: {} the exclude block for {}",
                    if on { "add" } else { "remove" },
                    WORKSPACE_PATTERNS.join(", ")
                );
            }
            return Ok(());
        }
        if server {
            // The project setting decides; the server exclude list carries
            // the workspace paths, so the local block and opt-out go.
            super::env_cmd::set(
                api_url,
                WORKSPACE_SETTING,
                if on { "true" } else { "false" },
                false,
                assume_yes,
            )
            .await?;
            let workspace = std::env::current_dir()?;
            let (project_id, client) = super::env_cmd::connect(api_url)?;
            let export = client.export_agent_files(&project_id).await?;
            let report = apply_server_excludes(&workspace, &export.git_exclude);
            print_server_exclude_report(&report, export.shadow.as_deref());
            if on && untrack && report.error.is_none() {
                // Only the workspace paths of the list, also when they
                // were excluded before (an explicit repeat).
                let entries: Vec<String> = report
                    .entries
                    .iter()
                    .filter(|e| is_workspace_entry(e))
                    .cloned()
                    .collect();
                untrack_server_paths(&workspace, &entries)?;
            }
            let effective = export.shadow_workspace.unwrap_or(on);
            if !adopt_server_workspace(&workspace, effective) && !effective {
                if let Ok(Some(repo)) = repo_at(&workspace) {
                    print_add_hints(&untracked_patterns_in(WORKSPACE_PATTERNS, &repo.work_tree));
                }
            }
            println!(
                "{} Workspace shadow {}.",
                style("●").magenta().bold(),
                style(if effective { "enabled" } else { "disabled" }).bold()
            );
            return Ok(());
        }
        let exclude_path = current_repo()?.exclude;
        set_workspace_opt_out(&exclude_path, !on)?;
        if on {
            local_on(LocalTarget::Workspace, untrack, true)?;
        } else {
            workspace_off()?;
            println!(
                "  {}",
                style("nexus pull keeps it off, also for a workspace fork in shadow mode.").dim()
            );
        }
    }
    Ok(())
}

/// Whether workspace shadow was switched off locally (`nexus shadow off
/// --target workspace`); `nexus pull` then does not switch it on.
pub fn workspace_opted_out() -> bool {
    current_repo()
        .ok()
        .and_then(|r| read_exclude(&r.exclude).ok())
        .is_some_and(|c| has_opt_out(&c))
}

/// Hand the workspace target over to the server. Once `af_export` reports
/// `shadow_workspace`, its `git_exclude` list carries the workspace paths
/// while the effective value is true, so the local block and the local
/// opt-out line go. `effective` false prints a `git add` hint for paths that
/// are no longer excluded. Returns whether anything was removed.
pub fn adopt_server_workspace(workspace: &Path, effective: bool) -> bool {
    let Ok(Some(repo)) = repo_at(workspace) else {
        return false;
    };
    let removed = drop_local_workspace(&repo.exclude);
    if removed {
        println!(
            "   {} workspace shadow follows the project setting now ({}); local block removed from .git/info/exclude",
            style("~").bold().cyan(),
            if effective { "on" } else { "off" }
        );
        if !effective {
            print_add_hints(&untracked_patterns_in(WORKSPACE_PATTERNS, &repo.work_tree));
        }
    }
    removed
}

/// Remove the local workspace block and the opt-out line; whether the
/// file changed.
fn drop_local_workspace(exclude_path: &Path) -> bool {
    let Ok(content) = read_exclude(exclude_path) else {
        return false;
    };
    if !content.contains(WS_MARKER_START) && !has_opt_out(&content) {
        return false;
    }
    let cleaned = remove_block(&content, WS_MARKER_START, WS_MARKER_END);
    let mut lines: Vec<&str> = cleaned.lines().filter(|l| l.trim() != WS_OPT_OUT).collect();
    while lines.last().is_some_and(|l| l.trim().is_empty()) {
        lines.pop();
    }
    let mut out = lines.join("\n");
    if !out.is_empty() {
        out.push('\n');
    }
    fs::write(exclude_path, out).is_ok()
}

fn has_opt_out(content: &str) -> bool {
    content.lines().any(|l| l.trim() == WS_OPT_OUT)
}

/// Add or remove the workspace opt-out line.
fn set_workspace_opt_out(exclude_path: &Path, opt_out: bool) -> anyhow::Result<()> {
    let content = read_exclude(exclude_path)?;
    if has_opt_out(&content) == opt_out {
        return Ok(());
    }
    let mut lines: Vec<&str> = content.lines().filter(|l| l.trim() != WS_OPT_OUT).collect();
    if opt_out {
        lines.push(WS_OPT_OUT);
    }
    if let Some(parent) = exclude_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut out = lines.join("\n");
    if !out.is_empty() {
        out.push('\n');
    }
    fs::write(exclude_path, out)?;
    Ok(())
}

/// One line per target for `nexus shadow status`.
fn print_targets(level: Option<&str>, server_workspace: Option<bool>, exclude_path: &Path) {
    let content = fs::read_to_string(exclude_path).unwrap_or_default();
    let legacy = content.contains(MARKER_START);
    let workspace = content.contains(WS_MARKER_START);
    let row = |name: &str, on: bool, source: &str| {
        let state = if on {
            style("on ").green().bold()
        } else {
            style("off").dim()
        };
        println!("  {name:<10} {state}  {}", style(source).dim());
    };
    println!("{} Shadow targets:", style("●").cyan().bold());
    match level {
        Some(level) => {
            row(
                "agentic",
                matches!(level, "ai" | "nexus"),
                &format!("policy.shadow={level}"),
            );
        }
        None => row("agentic", legacy, "local shadow block"),
    }
    match server_workspace {
        Some(on) => row(
            "workspace",
            on,
            "policy.shadow_workspace, else the workspace fork",
        ),
        None => row(
            "workspace",
            workspace,
            if has_opt_out(&content) {
                "local exclude block (switched off locally)"
            } else {
                "local exclude block"
            },
        ),
    }
    match level {
        Some(level) => row("nexus", level == "nexus", &format!("policy.shadow={level}")),
        None => row("nexus", false, "needs policy.shadow on the backend"),
    }
    println!();
}

fn agentic_root_of(export: &nexus_core::api::AgentFileExportResponse) -> String {
    if export.agentic_root.is_empty() {
        ".nexus".to_string()
    } else {
        export.agentic_root.clone()
    }
}

/// `nexus shadow check`: scan with the project's shadow guard (from the
/// backend, or the copy cached by the last pull when it is unreachable).
/// Returns the exit code: 0 clean or no guard, 1 findings.
pub async fn check(api_url: &str, commits: usize, json: bool) -> anyhow::Result<i32> {
    let workspace = std::env::current_dir()?;
    let root = super::shadow_guard::repo_root(&workspace)
        .ok_or_else(|| anyhow::anyhow!("Not inside a Git repository."))?;
    let export = match super::env_cmd::connect(api_url) {
        Ok((project_id, client)) => client.export_agent_files(&project_id).await.ok(),
        Err(_) => None,
    };
    let guard = match &export {
        Some(e) => e.shadow_guard.clone(),
        None => {
            let cached = super::shadow_guard::cached_guard(&workspace);
            if cached.is_some() && !json {
                println!(
                    "   {} no linked project or backend unreachable; using the rules cached by the last nexus pull",
                    style("i").bold().blue()
                );
            }
            cached
        }
    };
    let Some(guard) = guard else {
        if json {
            println!("{}", serde_json::json!({ "guard": null, "clean": true }));
        } else {
            println!(
                "{} No shadow guard for this project (shadow level off, or a backend without it).",
                style("OK").bold().green()
            );
        }
        return Ok(0);
    };
    let report = super::shadow_guard::run_check(&root, &guard, commits)?;
    if json {
        let mut value = serde_json::to_value(&report)?;
        value["clean"] = serde_json::Value::Bool(report.is_clean());
        println!("{}", serde_json::to_string_pretty(&value)?);
    } else {
        super::shadow_guard::print_report(&report);
    }
    Ok(i32::from(!report.is_clean()))
}

/// `nexus shadow status`: the server level and its exclude block, then the
/// local blocks.
pub async fn status_with_server(api_url: &str) -> anyhow::Result<()> {
    let workspace = std::env::current_dir()?;
    let exclude_path = current_repo()?.exclude;
    let mut server_level = false;
    let export = match super::env_cmd::connect(api_url) {
        Ok((project_id, client)) => Some(client.export_agent_files(&project_id).await),
        Err(_) => None,
    };
    let ok = export.as_ref().and_then(|e| e.as_ref().ok());
    print_targets(
        ok.and_then(|e| e.shadow.as_deref()),
        ok.and_then(|e| e.shadow_workspace),
        &exclude_path,
    );
    if let Some(export) = export {
        match export {
            Ok(export) => {
                server_level = export.shadow.is_some();
                let level = export
                    .shadow
                    .as_deref()
                    .unwrap_or("not set (older backend)");
                println!(
                    "{} Server shadow level: {}",
                    style("●").cyan().bold(),
                    style(level).bold()
                );
                super::shadow_guard::print_state(
                    super::shadow_guard::repo_root(&workspace).as_deref(),
                    level,
                    export.shadow_guard.as_ref(),
                );
                println!();
                let entries = server_exclude_entries(&workspace);
                if entries.is_empty() {
                    println!(
                        "  {}",
                        style("No server exclude block (run nexus pull).").dim()
                    );
                } else {
                    println!("  Server exclude block:");
                    for e in entries {
                        println!("    {}", style(e).dim());
                    }
                }
            }
            Err(e) => println!(
                "{} Server shadow level unavailable: {}",
                style("○").dim(),
                e
            ),
        }
    }
    local_status(server_level)
}

