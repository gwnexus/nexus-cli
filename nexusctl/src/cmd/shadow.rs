/// Find the `.git` directory by walking up from CWD.
fn find_git_dir() -> anyhow::Result<PathBuf> {
    find_git_dir_from(std::env::current_dir()?)
}

/// Find the `.git` directory by walking up from `dir`.
fn find_git_dir_from(mut dir: PathBuf) -> anyhow::Result<PathBuf> {
    loop {
        let candidate = dir.join(".git");
        if candidate.is_dir() {
            return Ok(candidate);
        }
        if !dir.pop() {
            anyhow::bail!("Not inside a Git repository. Run this command from a Git working tree.");
        }
    }
}

/// Check whether a marker block is present in the exclude file.
fn is_block_active(exclude_path: &Path, marker_start: &str) -> bool {
    if !exclude_path.exists() {
        return false;
    }
    match fs::read_to_string(exclude_path) {
        Ok(content) => content.contains(marker_start),
        Err(_) => false,
    }
}

/// Remove a marker-delimited block from file content.
fn remove_block(content: &str, marker_start: &str, marker_end: &str) -> String {
    let mut result = String::with_capacity(content.len());
    let mut inside_block = false;

    for line in content.lines() {
        if line.trim() == marker_start {
            inside_block = true;
            continue;
        }
        if line.trim() == marker_end {
            inside_block = false;
            continue;
        }
        if !inside_block {
            result.push_str(line);
            result.push('\n');
        }
    }

    let trimmed = result.trim_end_matches('\n');
    if trimmed.is_empty() {
        String::new()
    } else {
        format!("{trimmed}\n")
    }
}

/// Write a marker-delimited exclude block to the exclude file.
fn write_exclude_block(
    exclude_path: &Path,
    marker_start: &str,
    marker_end: &str,
    patterns: &[&str],
) -> anyhow::Result<()> {
    let mut block = String::new();
    block.push('\n');
    block.push_str(marker_start);
    block.push('\n');
    for pat in patterns {
        block.push_str(pat);
        block.push('\n');
    }
    block.push_str(marker_end);
    block.push('\n');

    let mut existing = if exclude_path.exists() {
        fs::read_to_string(exclude_path)?
    } else {
        String::new()
    };
    existing.push_str(&block);
    fs::write(exclude_path, &existing)?;
    Ok(())
}

/// Run `git rm --cached` for each pattern that is currently tracked.
///
/// Skips any file that has a commit history on the current branch
/// (`git log -1 -- <file>` returns output). Removing such a file from the
/// index would stage a deletion that could be accidentally committed.
///
/// Skipped files are reported as warnings so the user can act manually
/// with `git rm --cached` if that is truly their intent.
fn untrack_patterns(patterns: &[&str]) -> anyhow::Result<usize> {
    let mut count = 0;
    for pat in patterns {
        let clean = pat.trim_end_matches('/');

        // Collect concrete paths matched by this pattern (handles dirs and globs).
        let matched_paths = resolve_tracked_paths(clean);

        for path in &matched_paths {
            if is_file_tracked_in_history(path) {
                eprintln!(
                    "  {} skipping '{}' — file has commit history on this branch (use 'git rm --cached {}' manually if intended)",
                    console::style("warning:").yellow().bold(),
                    path,
                    path,
                );
                continue;
            }

            let output = Command::new("git")
                .args(["rm", "-r", "--cached", "--ignore-unmatch", path])
                .output();
            if let Ok(o) = output {
                if o.status.success() {
                    let stdout = String::from_utf8_lossy(&o.stdout);
                    count += stdout.lines().filter(|l| !l.is_empty()).count();
                }
            }
        }

        // Also attempt the pattern itself for any unmatched cases (directories, etc.)
        // that resolve_tracked_paths may have missed — but only if no specific paths
        // were found (avoids double-processing).
        if matched_paths.is_empty() {
            let output = Command::new("git")
                .args(["rm", "-r", "--cached", "--ignore-unmatch", clean])
                .output();
            if let Ok(o) = output {
                if o.status.success() {
                    let stdout = String::from_utf8_lossy(&o.stdout);
                    count += stdout.lines().filter(|l| !l.is_empty()).count();
                }
            }
        }
    }
    Ok(count)
}

/// Return all paths under `pattern` that git currently tracks in the index.
fn resolve_tracked_paths(pattern: &str) -> Vec<String> {
    resolve_tracked_paths_in(pattern, None)
}

/// Inner implementation — `workdir` overrides CWD for testability.
fn resolve_tracked_paths_in(pattern: &str, workdir: Option<&Path>) -> Vec<String> {
    let mut cmd = Command::new("git");
    cmd.args(["ls-files", "--", pattern]);
    if let Some(dir) = workdir {
        cmd.current_dir(dir);
    }
    match cmd.output() {
        Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout)
            .lines()
            .filter(|l| !l.is_empty())
            .map(|l| l.to_string())
            .collect(),
        _ => Vec::new(),
    }
}

/// Returns `true` if `path` appears in the commit history of the current branch.
fn is_file_tracked_in_history(path: &str) -> bool {
    is_file_tracked_in_history_in(path, None)
}

/// Inner implementation — `workdir` overrides CWD for testability.
fn is_file_tracked_in_history_in(path: &str, workdir: Option<&Path>) -> bool {
    let mut cmd = Command::new("git");
    // --no-pager: `git log` can invoke a pager when core.pager/GIT_PAGER
    // forces one, which blocks on a keypress read from the controlling
    // terminal rather than erroring out (see dispatch 479a4ab5 / the
    // identical fix in run.rs's git helpers).
    cmd.args(["--no-pager", "log", "--oneline", "-1", "--", path]);
    if let Some(dir) = workdir {
        cmd.current_dir(dir);
    }
    cmd.output()
        .map(|o| o.status.success() && !o.stdout.is_empty())
        .unwrap_or(false)
}

/// Run `git add` for each pattern that exists on disk.
fn retrack_patterns(patterns: &[&str]) -> anyhow::Result<usize> {
    let mut count = 0;
    for pat in patterns {
        let clean = pat.trim_end_matches('/');
        let path = Path::new(clean);
        if path.exists() {
            let output = Command::new("git").args(["add", clean]).output();
            if let Ok(o) = output {
                if o.status.success() {
                    count += 1;
                }
            }
        }
    }
    Ok(count)
}

