//! `nexus shadow on|off [--target ...]|status|check`: hide what Nexus and
//! agentic tooling put into a repository.
//!
//! Three targets, switched together (default) or one by one with
//! `--target`:
//! - `agentic`: agentic files, git-excluded (`policy.shadow` `ai`);
//! - `nexus`: also Nexus internals in commit messages and tracked files
//!   (`policy.shadow` `nexus`, enforced by the shadow guard); it includes
//!   `agentic`;
//! - `workspace`: the devbox files (`devbox.json`, `devbox.lock`,
//!   `.devbox/`, `scripts/devbox/`): the project setting
//!   `policy.shadow_workspace` on backends that have it (the server exclude
//!   list then carries the paths), otherwise a local exclude block.
//!
//! The shadow level is a
//! project setting on the server (`policy.shadow`: `off` | `ai` | `nexus`)
//! and `nexus shadow` is a thin client of it: it sets the level, then
//! applies the server's `af_export.git_exclude` list as a managed block in
//! `.git/info/exclude` (local, never committed). `nexus pull` applies the
//! same block on every run. Files already tracked in git are never
//! untracked automatically; a `git rm -r --cached` hint is printed instead.
//!
//! Backends without `policy.shadow` (or an unlinked workspace) keep the
//! old local mode: `on` adds a fixed pattern block and untracks matching
//! files without history, `off` removes it and re-adds them.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use console::style;

